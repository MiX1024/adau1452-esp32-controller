/*
 * 5x7 点阵字库（7 字节/字符，行主序，bit4=最左列，bit0=最右列）
 *
 * ⚠️⚠️ 这是**手挑子集**，不是完整 ASCII！未收录的字符**渲染为空白（不是方框）**。
 *
 * 已收录的全部字符：
 *
 *     空格  .  +  -  :  >  %  0-9  A-Z  d
 *
 * 也就是说：
 *   - **小写字母只有 `d`**（因为 "dB" 要用），其余 `a b c e f ... z` 全是空白；
 *   - 括号、逗号、斜杠、下划线、`<` `=` `?` 等符号一律空白。
 *
 * 后果很隐蔽：写错大小写不会报错，屏幕上只是"少了一截"。
 * 实际踩过：屏幕上一行 41 个字符的全小写提示，最终只画出 45 个像素 ——
 * 因为里面只有三个字母 `d` 有字模，看起来就像屏幕坏了。
 *
 * → **屏幕文案一律用大写**，并且只用上表里的符号。
 *   新增文案前先对照上表检查一遍大小写与标点。
 */
